const norm = (s: string) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[‑’'`]/g, "")
    .replace(/[^a-z0-9+ ]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

// Full names plus the short name before " by " ("Oud Wood by Tom Ford" → "oud wood").
const KNOWN = new Set<string>();
for (const p of [...ESCALO_PRODUCTS, ...INSPIRED_PRODUCTS]) {
  const n = norm(p);
  KNOWN.add(n);
  const short = n.split(" by ")[0].trim();
  if (short.length >= 3) KNOWN.add(short);
  const noParen = norm(p.replace(/\(.*\)/, ""));
  if (noParen.length >= 3) KNOWN.add(noParen);
}

/** True when the text is (just) a known product name, e.g. "ALF", "alf classic", "Oud Wood". */
export function isKnownProduct(text: string): boolean {
  const n = norm(text.replace(/^\s*inspired\s*by\s*:?\s*/i, ""));
  return n.length >= 2 && KNOWN.has(n);
}
